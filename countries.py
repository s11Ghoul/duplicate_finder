# Build reverse lookup: country name (lowercase) -> code
_NAME_TO_CODE = {v["name"].lower(): k for k, v in COUNTRIES.items()}


def resolve_country(identifier: str) -> dict | None:
    """Resolve country by 2-letter code or name (case-insensitive).
    Returns the country config dict with added 'code' key, or None.
    """
    upper = identifier.strip().upper()
    if upper in COUNTRIES:
        return {**COUNTRIES[upper], "code": upper}

    lower = identifier.strip().lower()
    if lower in _NAME_TO_CODE:
        code = _NAME_TO_CODE[lower]
        return {**COUNTRIES[code], "code": code}

    # Partial match
    for name, code in _NAME_TO_CODE.items():
        if lower in name:
            return {**COUNTRIES[code], "code": code}

    return None


def list_countries() -> list[tuple[str, str]]:
    """Return sorted list of (code, name) tuples."""
    return sorted((k, v["name"]) for k, v in COUNTRIES.items())
